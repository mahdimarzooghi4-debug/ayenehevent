create extension if not exists pgcrypto;

create sequence if not exists public.registration_code_seq start with 128 increment by 1;
create sequence if not exists public.contact_code_seq start with 128 increment by 1;

create or replace function public.normalize_digits(value text)
returns text
language sql
immutable
as $$
  select translate(coalesce(value, ''), '۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩', '01234567890123456789');
$$;

create or replace function public.next_registration_tracking_code()
returns text
language sql
volatile
security definer
set search_path = public
as $$
  select 'AY-1405-' || lpad(nextval('public.registration_code_seq')::text, 5, '0');
$$;

create or replace function public.next_contact_request_code()
returns text
language sql
volatile
security definer
set search_path = public
as $$
  select 'تماس-' || lpad(nextval('public.contact_code_seq')::text, 4, '0');
$$;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  display_name text not null default 'مدیر سامانه',
  created_at timestamptz not null default now()
);

create table if not exists public.registrations (
  id uuid primary key default gen_random_uuid(),

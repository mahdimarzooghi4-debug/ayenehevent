create index if not exists contact_requests_status_idx on public.contact_requests(status);
create index if not exists contact_requests_phone_idx on public.contact_requests(phone);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.admin_users
    where user_id = auth.uid()
  );
$$;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create or replace function public.log_registration_status_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if old.status is distinct from new.status
     or old.admin_message is distinct from new.admin_message then
    insert into public.registration_status_history (
      registration_id,
      previous_status,
      new_status,
      message,
      changed_by
    ) values (
      new.id,
      old.status,
      new.status,
      new.admin_message,
      auth.uid()
    );
  end if;
  return new;
end;
$$;

create or replace function public.log_contact_status_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if old.status is distinct from new.status
     or old.internal_note is distinct from new.internal_note then
    insert into public.contact_status_history (
      contact_request_id,
      previous_status,
      new_status,
      internal_note,
      changed_by
    ) values (
      new.id,
      old.status,
      new.status,
      new.internal_note,
      auth.uid()
    );
  end if;
  return new;
end;
$$;


create table if not exists public.contact_requests (
  id uuid primary key default gen_random_uuid(),
  request_code text not null unique default public.next_contact_request_code(),
  full_name text not null,
  phone text not null,
  province text not null,
  city text not null,
  preferred_time text not null,
  subject text not null,
  note text,
  status text not null default 'جدید',
  internal_note text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.contact_status_history (
  id bigint generated by default as identity primary key,
  contact_request_id uuid not null references public.contact_requests(id) on delete cascade,
  previous_status text,
  new_status text not null,
  internal_note text,
  changed_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.app_settings (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);

create index if not exists registrations_created_at_idx on public.registrations(created_at desc);
create index if not exists registrations_status_idx on public.registrations(status);
create index if not exists registrations_phone_idx on public.registrations(phone);
